"""One way to open the database, whether it's SQLite on my Mac or Postgres on AWS.

    connect( "data/worth.db" )                      # SQLite file (the default, same as always)
    connect( "postgresql://aj:pw@localhost/aj" )    # Postgres (docker compose, or RDS on AWS)

Where it connects when you don't pass anything (see default_target):
    1. DATABASE_URL, if it's set
    2. DB_HOST + DB_USER + DB_PASSWORD (+ DB_NAME, DB_PORT), which is how AWS hands
       the RDS login to the containers
    3. data/worth.db

The rest of the code keeps writing SQLite-style SQL (`?` placeholders, INSERT OR IGNORE)
and the Postgres wrapper below translates it, so store.py and comments.py barely changed.
"""

from __future__ import annotations

import os
import re
import sqlite3
from pathlib import Path
from urllib.parse import quote

DEFAULT_SQLITE = "data/worth.db"


def default_target() -> str:
    if os.environ.get( "DATABASE_URL" ):
        return os.environ[ "DATABASE_URL" ]
    if os.environ.get( "DB_HOST" ):
        user = quote( os.environ.get( "DB_USER", "postgres" ), safe="" )
        pw = quote( os.environ.get( "DB_PASSWORD", "" ), safe="" )
        host, port = os.environ[ "DB_HOST" ], os.environ.get( "DB_PORT", "5432" )
        name = os.environ.get( "DB_NAME", "ajindex" )
        return f"postgresql://{user}:{pw}@{host}:{port}/{name}"
    return DEFAULT_SQLITE


def is_postgres( target ) -> bool:
    return str( target ).startswith( ( "postgres://", "postgresql://" ) )


def connect( target=None ):
    target = default_target() if target is None else target
    if is_postgres( target ):
        return PgConnection( str( target ) )
    Path( target ).parent.mkdir( parents=True, exist_ok=True )
    conn = sqlite3.connect( target )
    conn.row_factory = sqlite3.Row
    return conn


def dialect( conn ) -> str:
    """ "postgres" or "sqlite", for the rare spot where the SQL has to differ."""
    return "postgres" if isinstance( conn, PgConnection ) else "sqlite"


# ---------------------------------------------------------------- Postgres translation

def schema_for_postgres( sql: str ) -> str:
    """Turns the SQLite CREATE statements into Postgres ones. Only the few bits we use."""
    sql = sql.replace( "INTEGER PRIMARY KEY", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" )
    sql = sql.replace( "CREATE VIEW IF NOT EXISTS", "CREATE OR REPLACE VIEW" )
    sql = re.sub( r"\bREAL\b", "DOUBLE PRECISION", sql )
    return sql


def query_for_postgres( sql: str ) -> str:
    """`?` placeholders -> `%s`, and INSERT OR IGNORE -> ON CONFLICT DO NOTHING."""
    sql = sql.replace( "%", "%%" )         # a real % has to be doubled once we use %s
    sql = sql.replace( "?", "%s" )
    if re.match( r"\s*INSERT OR IGNORE", sql, re.I ):
        sql = re.sub( r"INSERT OR IGNORE", "INSERT", sql, count=1, flags=re.I ).rstrip().rstrip( ";" )
        sql += " ON CONFLICT DO NOTHING"
    return sql


class Row( tuple ):
    """A row you can read by position (r[ 0 ]) or by name (r[ "title" ]), like sqlite3.Row."""

    def __new__( cls, values, names ):
        row = super().__new__( cls, values )
        row._names = names
        return row

    def __getitem__( self, key ):
        if isinstance( key, str ):
            return tuple.__getitem__( self, self._names.index( key ) )
        return tuple.__getitem__( self, key )

    def keys( self ):
        return list( self._names )


def _row_factory( cursor ):
    names = [ c.name for c in cursor.description ] if cursor.description else []
    return lambda values: Row( values, names )


class PgConnection:
    """Wraps a psycopg connection so it acts enough like sqlite3 for our code."""

    dialect = "postgres"

    def __init__( self, url: str ):
        import psycopg   # only needed when we're actually on Postgres
        self.raw = psycopg.connect( url, row_factory=_row_factory )

    def execute( self, sql: str, params=() ):
        cur = self.raw.cursor()
        if params:
            cur.execute( query_for_postgres( sql ), params )
        else:
            # no params = psycopg won't touch % signs, so only swap the INSERT OR IGNORE bit
            cur.execute( query_for_postgres( sql ).replace( "%%", "%" ) )
        return cur

    def executemany( self, sql: str, rows ):
        rows = list( rows )
        cur = self.raw.cursor()
        if rows:
            cur.executemany( query_for_postgres( sql ), rows )
        return cur

    def executescript( self, sql: str ):
        # psycopg can run a bunch of statements at once as long as there are no params
        self.raw.execute( schema_for_postgres( sql ) )
        self.raw.commit()

    def commit( self ):
        self.raw.commit()

    def rollback( self ):
        self.raw.rollback()

    def close( self ):
        self.raw.close()

    def __enter__( self ):
        return self

    def __exit__( self, *exc ):
        self.close()
